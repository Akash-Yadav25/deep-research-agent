"""Pydantic schemas for structured LLM interactions and outputs."""

from __future__ import annotations

from typing import Literal
from pydantic import BaseModel, Field


class ClarificationResult(BaseModel):
    """Result of the clarify_with_user step."""

    needs_clarification: bool = Field(
        description="Whether the research topic is ambiguous or underspecified and requires disambiguation."
    )
    clarification_question: str | None = Field(
        default=None,
        description="Clear, specific question to ask the user if clarification is needed.",
    )
    refined_topic: str = Field(
        description="Refined and disambiguated research prompt incorporating assumptions."
    )
    assumptions: list[str] = Field(
        default_factory=list,
        description="List of domain assumptions adopted to ground the research scope.",
    )


class ResearchQuestion(BaseModel):
    """A single subtopic research inquiry."""

    question: str = Field(description="The specific research question to be investigated.")
    search_queries_web: list[str] = Field(
        default_factory=list,
        description="2 to 4 optimized web search queries targeting search engines (Tavily).",
    )
    search_queries_arxiv: list[str] = Field(
        default_factory=list,
        description="1 to 3 academic keyword queries targeting arXiv preprints.",
    )
    priority: int = Field(
        default=1,
        ge=1,
        le=5,
        description="Investigation priority from 1 (crucial) to 5 (optional).",
    )


class ResearchBrief(BaseModel):
    """Structured research plan generated by write_research_brief."""

    original_topic: str = Field(description="The user's initial input prompt.")
    refined_topic: str = Field(description="Clarified, domain-focused research topic title.")
    detected_language: str = Field(
        default="en",
        description="ISO 639-1 language code of the topic (e.g. 'en', 'ja', 'es').",
    )
    research_questions: list[ResearchQuestion] = Field(
        default_factory=list,
        description="Set of prioritized research questions covering multiple angles.",
    )
    report_structure: list[str] = Field(
        default_factory=list,
        description="Proposed section headings forming the final report structure.",
    )
    key_terms: list[str] = Field(
        default_factory=list,
        description="Core terminology and synonyms for query expansion and retrieval.",
    )


class DraftSection(BaseModel):
    """A section in the skeleton draft report."""

    heading: str = Field(description="Section heading or title.")
    hypothesis: str = Field(
        description="Initial hypothesis, premise, or thesis to explore in this section."
    )
    open_questions: list[str] = Field(
        default_factory=list,
        description="Specific empirical or conceptual questions that require cited evidence.",
    )


class DraftReport(BaseModel):
    """Skeleton report generated by write_draft_report."""

    title: str = Field(description="Working title of the comprehensive research report.")
    abstract: str = Field(description="Executive summary draft outlining the expected scope.")
    sections: list[DraftSection] = Field(
        default_factory=list,
        description="Sequential list of draft report sections.",
    )


class SupervisorDecision(BaseModel):
    """Structured routing decision emitted by the supervisor node."""

    reasoning: str = Field(
        description="Brief step-by-step reasoning evaluating current research state and gaps."
    )
    action: Literal["web_research", "paper_research", "DONE"] = Field(
        description="Selected platform action: 'web_research', 'paper_research', or 'DONE'."
    )
    target_questions: list[str] = Field(
        default_factory=list,
        description="Research questions being targeted in this iteration.",
    )
    search_queries: list[str] = Field(
        default_factory=list,
        description="Search queries dispatched to the selected domain worker.",
    )


class EvaluationResult(BaseModel):
    """Coverage and sufficiency assessment produced by the evaluation node."""

    coverage_score: int = Field(
        ge=1,
        le=10,
        description="1-10 assessment of evidence coverage across the research brief.",
    )
    gaps: list[str] = Field(
        default_factory=list,
        description="Identified evidence voids or unaddressed research questions.",
    )
    sufficient: bool = Field(
        description="True if evidence is sufficient to assemble the final report.",
    )
    next_priority: str | None = Field(
        default=None,
        description="Highest priority gap to investigate if evidence is insufficient.",
    )
